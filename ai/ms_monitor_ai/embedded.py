"""Export a bounded random forest to standalone C++ for the ESP32."""

import hashlib
import json

import numpy as np
import pandas as pd


EMBEDDED_FEATURES = ("ambient_temp_c", "ambient_rh_pct", "grain_temp_c", "grain_air_delta_c")
RISK_WEIGHTS = {"low": 0.0, "moderate": 0.33, "high": 0.66, "critical": 1.0}


def build_embedded_features(frame: pd.DataFrame) -> pd.DataFrame:
    # Match the sensor floats and float subtraction performed in the firmware.
    air = frame["ambient_temp_c"].to_numpy(dtype=np.float32)
    humidity = frame["ambient_rh_pct"].to_numpy(dtype=np.float32)
    grain = frame["grain_temp_c"].to_numpy(dtype=np.float32)
    values = np.column_stack((air, humidity, grain, grain - air))
    if not np.isfinite(values).all():
        raise ValueError("Embedded model inputs must be finite")
    return pd.DataFrame(values, columns=EMBEDDED_FEATURES, index=frame.index)


def export_forest(model) -> tuple[str, dict]:
    classes = [str(value) for value in model.classes_]
    if set(classes) != set(RISK_WEIGHTS) or model.n_features_in_ != len(EMBEDDED_FEATURES):
        raise ValueError("Expected four risk classes and four sensor features")
    nodes = []
    roots = []
    for estimator in model.estimators_:
        tree = estimator.tree_
        offset = len(nodes)
        roots.append(offset)
        for index in range(tree.node_count):
            leaf = tree.children_left[index] < 0
            values = tree.value[index][0]
            probabilities = (values / values.sum()).tolist() if leaf else [0.0] * len(classes)
            nodes.append({
                "threshold": float(tree.threshold[index]) if not leaf else 0.0,
                "left": int(tree.children_left[index]) + offset if not leaf else -1,
                "right": int(tree.children_right[index]) + offset if not leaf else -1,
                "feature": int(tree.feature[index]) if not leaf else -1,
                "probabilities": probabilities,
            })
    if len(nodes) > 32767:
        raise ValueError("Model exceeds the signed 16-bit node index budget")
    signature = json.dumps(dict(nodes=nodes, roots=roots, classes=classes, features=EMBEDDED_FEATURES,
                                risk_weights=RISK_WEIGHTS, preprocessing="sensors-float32-delta-v1"),
                           sort_keys=True, separators=(",", ":"))
    version = "embedded-rf-" + hashlib.sha256(signature.encode()).hexdigest()[:12]
    lines = [
        "// Generated by ai/train_embedded.py. Do not edit model parameters manually.",
        "#pragma once", "#include <stdint.h>", "namespace ms_monitor_ai {",
        f'constexpr char kModelVersion[] = "{version}";',
        f"constexpr unsigned kFeatureCount = {len(EMBEDDED_FEATURES)};",
        f"constexpr unsigned kClassCount = {len(classes)};",
        f"constexpr unsigned kTreeCount = {len(roots)};",
        "struct RiskNode { double threshold; int16_t left; int16_t right; int8_t feature; double probabilities[kClassCount]; };",
        "static const char* const kClassNames[] = {" + ",".join(json.dumps(value) for value in classes) + "};",
        "static const double kRiskWeights[] = {" + ",".join(repr(RISK_WEIGHTS[value]) for value in classes) + "};",
        "static const RiskNode kNodes[] = {",
    ]
    for node in nodes:
        probabilities = ", ".join(repr(value) for value in node["probabilities"])
        lines.append("  {%s, %d, %d, %d, {%s}}," %
                     (repr(node["threshold"]), node["left"], node["right"], node["feature"], probabilities))
    lines += ["};", "static const int16_t kRoots[] = {" + ",".join(map(str, roots)) + "};",
              "constexpr unsigned kModelBytes = sizeof(kNodes) + sizeof(kRoots);",
              'static_assert(kModelBytes <= 256 * 1024, "Embedded forest exceeds 256 KiB model budget");',
              "}  // namespace ms_monitor_ai", ""]
    return "\n".join(lines), dict(model_version=version, trees=len(roots), nodes=len(nodes),
                                 features=list(EMBEDDED_FEATURES), classes=classes)
